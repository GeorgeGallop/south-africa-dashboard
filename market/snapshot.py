"""Capture the market payloads into a static file for server-less page loads.

The dashboard's prices come from ``server.py`` over ``/api/market/*``. When a
page is opened through a plain static server -- which is how the pages are read
most of the time -- that endpoint does not exist, ``/api/market/*`` answers 404
and the page falls back to the stored capture written here.

Two files are written from the same capture:

``market-snapshot.js``
    The long-standing form, assigning ``window.MARKET_SNAPSHOT``. A ``<script>``
    tag always loads it, including over ``file://`` where ``fetch`` of a local
    file is blocked.
``market-snapshot.json``
    The same document as plain JSON. The page fetches it with ``no-store`` when
    the copy already in the page is from an earlier JSE session, so regenerating
    the snapshot is enough -- a plain browser refresh picks it up without a hard
    reload clearing the cached script.

The capture is stamped with the JSE session it belongs to, so the page can say
which session's close it is showing rather than just when the file was written.

Run from the dashboard directory:

    py -m market.snapshot
"""
import json
import time
from pathlib import Path

from . import service, sessions
from .settings import DATA_DIR

SNAPSHOT_FILE = DATA_DIR / "market-snapshot.js"
SNAPSHOT_JSON_FILE = DATA_DIR / "market-snapshot.json"

#: Series the page reads, in the order the header lists them.
SERIES = ("equities", "fx", "bonds")

#: Builders keyed by series name, matching server.py's MARKET_BUILDERS.
BUILDERS = {
    "equities": service.get_equities,
    "fx": service.get_fx,
    "bonds": service.get_bonds,
}


def build_snapshot(force=True):
    """Return ``{series: envelope}`` for every series the page displays."""
    captured = {}
    for series in SERIES:
        captured[series] = BUILDERS[series](force)

    now = time.time()
    session_key = sessions.session_key(now)
    return {
        "generatedAt": sessions.format_sast(now),
        "generatedAtEpoch": int(now),
        "sessionKey": session_key,
        "sessionLabel": sessions.session_label(session_key),
        "series": captured,
    }


def _serialise(snapshot):
    return json.dumps(snapshot, separators=(",", ":"), ensure_ascii=False)


def write_snapshot(snapshot, path=None):
    """Write the capture as both the script and the plain-JSON sibling."""
    script_path = Path(path or SNAPSHOT_FILE)
    script_path.parent.mkdir(parents=True, exist_ok=True)

    body = _serialise(snapshot)
    lines = [
        "/* Stored market snapshot -- generated by `py -m market.snapshot`.",
        "   Used only when the live dashboard API is unreachable, so the page",
        "   shows the last settled JSE close instead of an empty panel.",
        "   Generated: " + snapshot["generatedAt"] + " */",
        "window.MARKET_SNAPSHOT = " + body + ";",
        "",
    ]
    script_path.write_text("\n".join(lines), encoding="utf-8")

    json_path = script_path.with_suffix(".json")
    json_path.write_text(body, encoding="utf-8")

    return script_path, json_path


def main():
    snapshot = build_snapshot(force=True)
    script_path, json_path = write_snapshot(snapshot)

    equities = snapshot["series"]["equities"]["data"]
    print(f"Snapshot written: {script_path}")
    print(f"                  {json_path}")
    print(f"  Generated:  {snapshot['generatedAt']}")
    print(f"  Session:    {snapshot['sessionLabel']} ({snapshot['sessionKey']})")
    print(f"  Equities:   {equities['coverage']['priced']} listings priced")
    print(f"  Priced at:  {equities['asOf']}")


if __name__ == "__main__":
    main()
